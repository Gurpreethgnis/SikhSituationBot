const TranslationContext = createContext(null)

export function TranslationProvider({ children }) {
  const [uiLanguage, setUiLanguage] = useState('en')

  const t = useCallback((key) => {
    const langTranslations = translations[uiLanguage] || translations.en
    return langTranslations[key] || translations.en[key] || key
  }, [uiLanguage])

  const changeUiLanguage = useCallback((lang) => {
    if (translations[lang]) {
      setUiLanguage(lang)
      try {
        localStorage.setItem('sikh_bot_ui_language', lang)
      } catch {
        /* ignore */
      }
    }
  }, [])

  React.useEffect(() => {
    try {
      const saved = localStorage.getItem('sikh_bot_ui_language')
      if (saved && translations[saved]) {
        setUiLanguage(saved)
      }
    } catch {
      /* ignore */
    }
  }, [])

  return (
    <TranslationContext.Provider value={{ uiLanguage, changeUiLanguage, t }}>
      {children}
    </TranslationContext.Provider>
  )
}

export function useTranslation() {
  const ctx = useContext(TranslationContext)
  if (!ctx) throw new Error('useTranslation must be used within TranslationProvider')
  return ctx
}

