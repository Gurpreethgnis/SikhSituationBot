#!/usr/bin/env node
/**
 * Generate mobile/.env from the repo root .env using the same values as the web app where names differ.
 * Run from mobile/: npm run sync-env
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.join(__dirname, '..');
const repoRoot = path.join(mobileRoot, '..');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  const text = fs.readFileSync(filePath, 'utf8');
  for (const line of text.split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = t.indexOf('=');
    if (eq === -1) continue;
    const key = t.slice(0, eq).trim();
    let val = t.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

function serializeEnv(obj) {
  const lines = [
    '# Generated by: npm run sync-env (from mobile/)',
    '# Source: ../../.env — re-run after changing root env. Do not commit this file.',
    '',
  ];
  const keys = Object.keys(obj).sort();
  for (const k of keys) {
    const v = obj[k];
    if (v === undefined || v === '') continue;
    const needsQuote = /[\s#]/.test(v);
    lines.push(`${k}=${needsQuote ? JSON.stringify(v) : v}`);
  }
  lines.push('');
  return lines.join('\n');
}

const root = parseEnvFile(path.join(repoRoot, '.env'));
const existingMobile = parseEnvFile(path.join(mobileRoot, '.env'));

function normalizeApiUrl(nextUrl, flaskUrl, fallback) {
  const raw = (nextUrl || flaskUrl || fallback || '').trim();
  if (!raw || raw.toLowerCase() === 'same-origin') {
    const flask = (flaskUrl || '').trim().replace(/\/$/, '');
    if (flask && flask.toLowerCase() !== 'same-origin') return flask;
    return 'http://localhost:5000';
  }
  return raw.replace(/\/$/, '');
}

// Mobile cannot use Next "same-origin"; use FLASK_API_URL when NEXT_PUBLIC_API_URL is same-origin or empty.
const apiUrl = normalizeApiUrl(
  root.NEXT_PUBLIC_API_URL,
  root.FLASK_API_URL,
  existingMobile.EXPO_PUBLIC_API_URL
);

const mobile = {
  ...existingMobile,
  EXPO_PUBLIC_API_URL: apiUrl,
  EXPO_PUBLIC_FLASK_INTERNAL_KEY:
    root.FLASK_INTERNAL_API_KEY || existingMobile.EXPO_PUBLIC_FLASK_INTERNAL_KEY || '',
  EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID:
    root.GOOGLE_CLIENT_ID || existingMobile.EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID || '',
};

// Preserve explicit mobile OAuth clients if already set
for (const k of [
  'EXPO_PUBLIC_GOOGLE_EXPO_CLIENT_ID',
  'EXPO_PUBLIC_GOOGLE_IOS_CLIENT_ID',
  'EXPO_PUBLIC_GOOGLE_ANDROID_CLIENT_ID',
]) {
  if (existingMobile[k]) mobile[k] = existingMobile[k];
}

const outPath = path.join(mobileRoot, '.env');
fs.writeFileSync(outPath, serializeEnv(mobile), 'utf8');
console.log(`Wrote ${outPath}`);
console.log('  EXPO_PUBLIC_API_URL ← NEXT_PUBLIC_API_URL, or FLASK_API_URL if Next uses same-origin');
console.log('  EXPO_PUBLIC_FLASK_INTERNAL_KEY ← FLASK_INTERNAL_API_KEY');
console.log('  EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID ← GOOGLE_CLIENT_ID');
console.log('Restart Expo with: npx expo start --clear');
